def species_name(species_id: int) -> str:
    """Internal species index -> display name. Unknown IDs shown as hex."""
    return SPECIES_NAMES.get(species_id, f"#{species_id:02X}")


def type_name(type_id: int) -> str:
    return TYPE_NAMES.get(type_id, f"?{type_id:02X}")


def map_name(map_id: int) -> str:
    return MAP_NAMES.get(map_id, f"Map 0x{map_id:02X}")


def status_text(status_byte: int) -> str:
    """Decode the Gen 1 status condition byte into a short label."""
    if status_byte == 0:
        return "OK"
    parts = []
    sleep_turns = status_byte & 0b111
    if sleep_turns:
        parts.append(f"SLP({sleep_turns})")
    if status_byte & 0b0000_1000:
        parts.append("PSN")
    if status_byte & 0b0001_0000:
        parts.append("BRN")
    if status_byte & 0b0010_0000:
        parts.append("FRZ")
    if status_byte & 0b0100_0000:
        parts.append("PAR")
    return "/".join(parts) if parts else "OK"
